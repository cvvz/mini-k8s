// The node containers Compose starts: the control-plane node, which runs the
// control plane as static Pods, and the workers worker-1 to worker-N.
const controlPlane = "control-plane"

// compose.yaml defines two workers; `kk cluster up --workers N` records
// another count in workersFile and generates overrideFile from it, which
// every Compose command also reads.
const (
	defaultWorkers = 2
	maxWorkers     = 10
	workersFile    = ".mini-k8s/workers"
	overrideFile   = ".mini-k8s/compose.workers.yaml"
)

func workerNames(n int) []string {
	names := make([]string, n)
	for i := range names {
		names[i] = fmt.Sprintf("worker-%d", i+1)
	}
	return names
}

func nodeNames(workers int) []string { return append([]string{controlPlane}, workerNames(workers)...) }

// workerIndex returns K for a node named worker-K.
func workerIndex(name string) (int, bool) {
	s, ok := strings.CutPrefix(name, "worker-")
	if !ok {
		return 0, false
	}
	k, err := strconv.Atoi(s)
	return k, err == nil && k > 0 && strconv.Itoa(k) == s
}

func parseWorkers(s string) (int, error) {
	n, err := strconv.Atoi(strings.TrimSpace(s))
	if err != nil || n < 1 || n > maxWorkers {
		return 0, fmt.Errorf("invalid worker count %q: must be 1 to %d", strings.TrimSpace(s), maxWorkers)
	}
	return n, nil
}

// loadWorkers returns the worker count of the last `kk cluster up`.
func loadWorkers(root string) (int, error) {
	data, err := os.ReadFile(filepath.Join(root, workersFile))
	if errors.Is(err, os.ErrNotExist) {
		return defaultWorkers, nil
	}
	if err != nil {
		return 0, err
	}
	n, err := parseWorkers(string(data))
	if err != nil {
		return 0, fmt.Errorf("%s: %w", workersFile, err)
	}
	return n, nil
}

// workersOverride is the Compose override for n workers: worker-3 and up
// are copies of worker-1 with their own name and disk, and with a single
// worker, worker-2 runs no container.
func workersOverride(n int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by kk cluster up for %d worker(s); do not edit.\n", n)
	switch {
	case n == 1:
		b.WriteString("services:\n  worker-2:\n    deploy:\n      replicas: 0\n")
	case n == defaultWorkers:
		b.WriteString("services: {}\n")
	default:
		extra := workerNames(n)[defaultWorkers:]
		b.WriteString("services:\n")
		for _, w := range extra {
			fmt.Fprintf(&b, "  %[1]s:\n    extends:\n      file: compose.yaml\n      service: worker-1\n    hostname: %[1]s\n"+
				"    environment:\n      MINI_NODE: %[1]s\n    volumes:\n      - %[1]s-var:/var\n", w)
		}
		b.WriteString("volumes:\n")
		for _, w := range extra {
			fmt.Fprintf(&b, "  %s-var:\n", w)
		}
	}
	return b.String()
}

// nodeContainer is the Compose container of a node, e.g. mini-k8s-worker-1-1.
func nodeContainer(node string) string { return "mini-k8s-" + node + "-1" }

// nodeVolume is the Docker volume holding a node's /var.
func nodeVolume(node string) string { return "mini-k8s_" + node + "-var" }

// images are built from build/images/<dir>/Dockerfile by `kk cluster up`.
var images = []struct{ tag, dir string }{
	{"mini-k8s:local", "mini"},
	{"mini-k8s-pause:local", "pause"},
	{"mini-k8s-node:local", "node"},
	{"mini-k8s-kube-proxy:local", "kube-proxy"},
	{"mini-k8s-etcd:3.5.17", "etcd"},
}

// nodeImages are preloaded into every node's containerd: the sandbox (pause)
// image, the image of the components, examples and e2e workloads, and
// kube-proxy's; the control-plane node also gets the etcd image.
var nodeImages = []string{"mini-k8s:local", "mini-k8s-pause:local", "mini-k8s-kube-proxy:local"}

const etcdImage = "mini-k8s-etcd:3.5.17"

type cluster struct {
	run func(context.Context, string, ...string) (string, error)
	// pipe runs `from | to` and returns the output of to.
	pipe    func(ctx context.Context, from, to []string) (string, error)
	client  *client.Client
	out     io.Writer
	cleanup func() error
	// addons is the directory of add-on manifests applied once the nodes
	// are Ready (build/manifests/addons); empty skips the phase.
	addons string
	// root is the project directory; workers the number of worker nodes.
	root    string
	workers int
}

// compose returns a docker compose command line over compose.yaml and the
// generated worker override.
func (c cluster) compose(args ...string) []string {
	return append([]string{"docker", "compose", "-f", "compose.yaml", "-f", overrideFile}, args...)
}

// setWorkers records the worker count and regenerates the override.
func (c *cluster) setWorkers(n int, record bool) error {
	c.workers = n
	if record {
		if err := os.WriteFile(filepath.Join(c.root, workersFile), []byte(strconv.Itoa(n)+"\n"), 0o644); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(c.root, overrideFile), []byte(workersOverride(n)), 0o644)
}

func projectRoot() (string, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return "", err
	}
	if isProject(cwd) {
		return cwd, nil
	}
	executable, err := os.Executable()
	if err != nil {
		return "", err
	}
	executable, err = filepath.EvalSymlinks(executable)
	if err != nil {
		return "", err
	}
	if filepath.Base(filepath.Dir(executable)) == "bin" {
		root := filepath.Dir(filepath.Dir(executable))
		if isProject(root) {
			return root, nil
		}
	}
	return "", errors.New("run kk from the mini-k8s project root, or use the project's bin/kk")
}

func isProject(root string) bool {
	for _, name := range []string{"go.mod", "compose.yaml"} {
		info, err := os.Stat(filepath.Join(root, name))
		if err != nil || !info.Mode().IsRegular() {
			return false
		}
	}
	module, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return false
	}
	for _, line := range strings.Split(string(module), "\n") {
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == "module" {
			return fields[1] == "mini-k8s"
		}
	}
	return false
}

func loadToken(root string, create bool) (string, error) {
	dir := filepath.Join(root, ".mini-k8s")
	path := filepath.Join(dir, "token")
	if create {
		if err := os.MkdirAll(dir, 0700); err != nil {
			return "", err
		}
	}
	dirInfo, err := os.Lstat(dir)
	if err != nil {
		return "", fmt.Errorf("token directory: %w; run kk cluster up first", err)
	}
	if !dirInfo.IsDir() || dirInfo.Mode()&os.ModeSymlink != 0 {
		return "", errors.New("token directory must be a real directory")
	}
	if create {
		var secret [32]byte
		if _, err := rand.Read(secret[:]); err != nil {
			return "", err
		}
		file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if err == nil {
			_, writeErr := io.WriteString(file, hex.EncodeToString(secret[:])+"\n")
			closeErr := file.Close()
			if err := errors.Join(writeErr, closeErr); err != nil {
				return "", fmt.Errorf("write token: %w", err)
			}
		} else if !errors.Is(err, os.ErrExist) {
			return "", err
		}
	}
	info, err := os.Lstat(path)
	if err != nil {
		return "", fmt.Errorf("read token: %w; run kk cluster up first", err)
	}
	if !info.Mode().IsRegular() {
		return "", errors.New("token must be a regular file, not a symlink")
	}
	if err := os.Chmod(path, 0600); err != nil {
		return "", err
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	token := strings.TrimSpace(string(data))
	if token == "" || strings.ContainsAny(token, " \t\r\n") {
		return "", errors.New("existing token is empty or invalid; refusing to replace it")
	}
	return token, nil
}

func localSocket(endpoint string) (string, error) {
	u, err := url.Parse(strings.TrimSpace(endpoint))
	if err != nil {
		return "", err
	}
	if u.Scheme != "unix" || u.Host != "" || u.User != nil || !filepath.IsAbs(u.Path) || u.RawQuery != "" || u.Fragment != "" {
		return "", fmt.Errorf("Docker endpoint %q is not a local Unix socket; TCP/SSH/remote engines are refused", endpoint)
	}
	return u.Path, nil
}

func checkDockerDaemon(ctx context.Context, run func(context.Context, string, ...string) (string, error)) error {
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	output, err := run(ctx, "docker", "info", "--format", "{{.ServerVersion}}")
	if err != nil {
		return fmt.Errorf("Docker CLI preflight failed: %w; no build/start attempted", errors.Join(err, ctx.Err()))
	}
	if strings.TrimSpace(output) == "" {
		return errors.New("Docker CLI preflight returned no server version; no build/start attempted")
	}
	return nil
}

func commandRunner(root string, env []string) func(context.Context, string, ...string) (string, error) {
	return func(ctx context.Context, name string, args ...string) (string, error) {
		command := exec.CommandContext(ctx, name, args...)
		command.Dir = root
		command.Env = env
		data, err := command.CombinedOutput()
		if err != nil {
			return "", fmt.Errorf("%s %s: %w\n%s", name, strings.Join(args, " "), err, data)
		}
		return string(data), nil
	}
}

func commandPipe(root string, env []string) func(context.Context, []string, []string) (string, error) {
	return func(ctx context.Context, from, to []string) (string, error) {
		producer := exec.CommandContext(ctx, from[0], from[1:]...)
		consumer := exec.CommandContext(ctx, to[0], to[1:]...)
		for _, c := range []*exec.Cmd{producer, consumer} {
			c.Dir, c.Env = root, env
		}
		var producerErr strings.Builder
		producer.Stderr = &producerErr
		stream, err := producer.StdoutPipe()
		if err != nil {
			return "", err
		}
		consumer.Stdin = stream
		var output strings.Builder
		consumer.Stdout, consumer.Stderr = &output, &output
		if err := producer.Start(); err != nil {
			return "", err
		}
		consumeErr := consumer.Run()
		if consumeErr != nil {
			_ = producer.Process.Kill()
		}
		produceErr := producer.Wait()
		if consumeErr != nil || produceErr != nil {
			return "", fmt.Errorf("%s | %s: %w\n%s%s", strings.Join(from, " "), strings.Join(to, " "),
				errors.Join(produceErr, consumeErr), producerErr.String(), output.String())
		}
		return output.String(), nil
	}
}

func withEnv(env []string, key, value string) []string {
	result := make([]string, 0, len(env)+1)
	for _, entry := range env {
		if !strings.HasPrefix(entry, key+"=") {
			result = append(result, entry)
		}
	}
	return append(result, key+"="+value)
}

func newCluster(ctx context.Context, root, token string, out io.Writer) (cluster, error) {
	workers, err := loadWorkers(root)
	if err != nil {
		return cluster{}, err
	}
	env := os.Environ()
	run := commandRunner(root, env)
	endpoint := os.Getenv("DOCKER_HOST")
	dockerContext := os.Getenv("DOCKER_CONTEXT")
	if dockerContext != "" || endpoint == "" {
		if dockerContext == "" {
			value, err := run(ctx, "docker", "context", "show")
			if err != nil {
				return cluster{}, err
			}
			dockerContext = strings.TrimSpace(value)
		}
		value, err := run(ctx, "docker", "context", "inspect", dockerContext, "--format", "{{.Endpoints.docker.Host}}")
		if err != nil {
			return cluster{}, err
		}
		endpoint = strings.TrimSpace(value)
	}
	// The cluster publishes its ports on 127.0.0.1, so only a local engine
	// yields a usable cluster.
	if _, err := localSocket(endpoint); err != nil {
		return cluster{}, err
	}
	env = withEnv(env, "MINI_TOKEN", token)
	var cleanup func() error
	switch os.Getenv("MINI_DOCKER_NO_CREDENTIALS") {
	case "", "0":
	case "1":
		env, cleanup, err = anonymousDockerEnv(root, endpoint, env)
		if err != nil {
			return cluster{}, err
		}
		if _, err := fmt.Fprintln(out, "Docker anonymous mode: credential helpers disabled for this command; user config unchanged"); err != nil {
			return cluster{}, errors.Join(err, cleanup())
		}
	default:
		return cluster{}, errors.New("MINI_DOCKER_NO_CREDENTIALS must be 0 or 1")
	}
	run = commandRunner(root, env)
	if err := checkDockerDaemon(ctx, run); err != nil {
		if cleanup != nil {
			err = errors.Join(err, cleanup())
		}
		return cluster{}, err
	}
	c := cluster{run: run, pipe: commandPipe(root, env), client: client.New(apiURL(), token), out: out, cleanup: cleanup,
		addons: filepath.Join(root, "build", "manifests", "addons"), root: root}
	if err := c.setWorkers(workers, false); err != nil {
		if cleanup != nil {
			err = errors.Join(err, cleanup())
		}
		return cluster{}, err
	}
	return c, nil
}

// up builds the images and starts (or updates) the cluster with the given
// number of workers. Workers beyond it are drained while the cluster still
// runs them, then removed with their disks and Node objects.
func (c cluster) up(ctx context.Context, workers int) error {
	// Node objects in etcd may still show heartbeats from before Compose
	// recreated the nodes: only heartbeats sent after this point count.
	since := time.Now()
	commands := [][]string{{"make", "build", "prepare-etcd"}}
	for _, image := range images {
		commands = append(commands, []string{"docker", "build", "-t", image.tag, "-f", "build/images/" + image.dir + "/Dockerfile", "."})
	}
	for _, command := range commands {
		if err := c.step(ctx, command); err != nil {
			return err
		}
	}
	if err := c.drainRemovedWorkers(ctx, workers); err != nil {
		return err
	}
	if err := c.setWorkers(workers, true); err != nil {
		return err
	}
	// Workers above the count are orphans of the project now (or, for
	// worker-2, scaled to zero): Compose removes their containers.
	if err := c.step(ctx, c.compose("up", "-d", "--pull", "never", "--remove-orphans")); err != nil {
		return err
	}
	if err := c.removeWorkerDisks(ctx); err != nil {
		return err
	}
	// The control plane's static Pods start as soon as their images arrive.
	// The node's disk keeps images across restarts, so they may already be
	// running from an older build: restart those (a kubeadm-style upgrade).
	if err := c.loadImages(ctx, append(append([]string{}, nodeImages...), etcdImage), controlPlane); err != nil {
		return err
	}
	if err := c.restartStaleSystemPods(ctx, controlPlane); err != nil {
		return err
	}
	if err := c.loadImages(ctx, nodeImages, workerNames(c.workers)...); err != nil {
		return err
	}
	for _, node := range workerNames(c.workers) {
		if err := c.restartStaleSystemPods(ctx, node); err != nil {
			return err
		}
	}
	waitCtx, cancel := context.WithTimeout(ctx, 2*time.Minute)
	defer cancel()
	if err := c.waitReady(waitCtx, since); err != nil {
		return err
	}
	if err := c.deleteRemovedNodes(ctx); err != nil {
		return err
	}
	if err := c.applyAddons(ctx); err != nil {
		return err
	}
	_, err := fmt.Fprintf(c.out, "mini-k8s ready: API http://127.0.0.1:18000; nodes %s Ready\n", strings.Join(nodeNames(c.workers), ", "))
	return err
}

// removedWorkers returns the workers numbered above the count, in order.
func removedWorkers(names []string, workers int) []string {
	var out []string
	for _, name := range names {
		if k, ok := workerIndex(name); ok && k > workers {
			out = append(out, name)
		}
	}
	slices.SortFunc(out, func(a, b string) int {
		i, _ := workerIndex(a)
		j, _ := workerIndex(b)
		return i - j
	})
	return out
}

// drainRemovedWorkers evicts the Pods of the workers about to be removed,
// as a cloud provider drains a node before deleting its VM. A cluster that
// is not running cannot be drained; the Pod garbage collector then deletes
// the Pods of those nodes once deleteRemovedNodes has deleted the nodes.
func (c cluster) drainRemovedWorkers(ctx context.Context, workers int) error {
	healthCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	err := c.client.Health(healthCtx)
	cancel()
	if err != nil {
		if workers >= c.workers {
			return nil // most likely nothing to drain
		}
		_, err := fmt.Fprintf(c.out, "Not draining the workers above %d: the API is unavailable (%v)\n", workers, err)
		return err
	}
	nodes, err := client.Nodes(c.client).List(ctx, client.ListOptions{})
	if err != nil {
		return err
	}
	var names []string
	ready := map[string]bool{}
	for i := range nodes.Items {
		names = append(names, nodes.Items[i].Name)
		ready[nodes.Items[i].Name] = corev1.IsNodeReady(&nodes.Items[i])
	}
	a := newApp(c.client, c.out, nil, args{})
	removed := removedWorkers(names, workers)
	// Cordon them all first, so Pods evicted from one do not move to
	// another; a failed drain undoes that and leaves the workers in place.
	var cordoned []string
	uncordon := func() error {
		var errs []error
		for _, name := range cordoned {
			if _, err := a.setUnschedulable(ctx, name, false); err != nil {
				errs = append(errs, err)
			}
		}
		return errors.Join(errs...)
	}
	for _, name := range removed {
		changed, err := a.setUnschedulable(ctx, name, true)
		if err != nil {
			return errors.Join(err, uncordon())
		}
		if changed {
			cordoned = append(cordoned, name)
		}
	}
	for _, name := range removed {
		if !ready[name] {
			// No kubelet would confirm the evictions: the Pod garbage
			// collector deletes its Pods once the node is deleted.
			if _, err := fmt.Fprintf(c.out, "Not draining %s: it is not Ready\n", name); err != nil {
				return err
			}
			continue
		}
		if _, err := fmt.Fprintf(c.out, "Draining %s\n", name); err != nil {
			return err
		}
		// The node goes away: Pods without a controller or with local
		// data cannot stay either.
		p := args{positional: []string{name}, values: map[string][]string{"timeout": {"2m"}},
			bools: map[string]bool{"force": true, "delete-emptydir-data": true, "ignore-daemonsets": true}}
		if err := a.drain(ctx, p); err != nil {
			return errors.Join(fmt.Errorf("drain %s: %w", name, err), uncordon())
		}
	}
	return nil
}

// deleteRemovedNodes deletes the Node objects of workers numbered above the
// worker count, as the cloud node controller deletes the Node of a deleted
// VM; the garbage collector then deletes their Leases and mirror Pods.
func (c cluster) deleteRemovedNodes(ctx context.Context) error {
	nodes, err := client.Nodes(c.client).List(ctx, client.ListOptions{})
	if err != nil {
		return err
	}
	var names []string
	for _, n := range nodes.Items {
		names = append(names, n.Name)
	}
	for _, name := range removedWorkers(names, c.workers) {
		if _, err := fmt.Fprintf(c.out, "Deleting node %s\n", name); err != nil {
			return err
		}
		if err := client.Nodes(c.client).Delete(ctx, name, nil); err != nil && !client.IsNotFound(err) {
			return err
		}
	}
	return nil
}

// removeWorkerDisks deletes the /var volumes of the project's workers
// numbered above the count, so a worker added again starts from a fresh disk.
func (c cluster) removeWorkerDisks(ctx context.Context) error {
	out, err := c.run(ctx, "docker", "volume", "ls", "-q", "--filter", "label=com.docker.compose.project=mini-k8s")
	if err != nil {
		return err
	}
	var names []string
	for _, volume := range strings.Fields(out) {
		if name, ok := strings.CutPrefix(volume, "mini-k8s_"); ok {
			if name, ok := strings.CutSuffix(name, "-var"); ok {
				names = append(names, name)
			}
		}
	}
	for _, name := range removedWorkers(names, c.workers) {
		if err := c.step(ctx, []string{"docker", "volume", "rm", "--force", nodeVolume(name)}); err != nil {
			return err
		}
	}
	return nil
}

// applyAddons applies the add-on manifests through the API, like kubeadm's
// addon phase installs CoreDNS: the cluster DNS runs as ordinary workloads.
func (c cluster) applyAddons(ctx context.Context) error {
	if c.addons == "" {
		return nil
	}
	if _, err := fmt.Fprintf(c.out, "Applying add-ons from %s\n", c.addons); err != nil {
		return err
	}
	a := newApp(c.client, c.out, nil, args{})
	return a.applyFiles(ctx, args{values: map[string][]string{"filename": {c.addons}}, bools: map[string]bool{}}, false)
}

func (c cluster) step(ctx context.Context, command []string) error {
	if _, err := fmt.Fprintf(c.out, "Running %s\n", strings.Join(command, " ")); err != nil {
		return err
	}
	output, err := c.run(ctx, command[0], command[1:]...)
	if err != nil {
		return err
	}
	_, err = io.WriteString(c.out, output)
	return err
}

// loadImages copies local Docker images into the containerd of the nodes,
// like `kind load docker-image`. A node's containerd may still be starting,
// so each import is retried for a while.
func (c cluster) loadImages(ctx context.Context, refs []string, nodes ...string) error {
	for _, node := range nodes {
		if _, err := fmt.Fprintf(c.out, "Loading %s into %s\n", strings.Join(refs, " "), node); err != nil {
			return err
		}
		from := append([]string{"docker", "save"}, refs...)
		to := []string{"docker", "exec", "-i", nodeContainer(node), "ctr", "-n", "k8s.io", "images", "import", "-"}
		deadline := time.Now().Add(time.Minute)
		for {
			_, err := c.pipe(ctx, from, to)
			if err == nil {
				break
			}
			if time.Now().After(deadline) {
				return fmt.Errorf("load images into %s: %w", node, err)
			}
			select {
			case <-ctx.Done():
				return ctx.Err()
			case <-time.After(2 * time.Second):
			}
		}
	}
	return nil
}

// restartStaleSystemPods stops a node's kube-system containers (the static
// Pods and add-ons such as the cluster DNS) whose image name now refers to
// another image than the one they run; the kubelet restarts them from the
// freshly loaded image.
func (c cluster) restartStaleSystemPods(ctx context.Context, name string) error {
	node := nodeContainer(name)
	out, err := c.run(ctx, "docker", "exec", node, "crictl", "ps", "-o", "json", "--label", "io.kubernetes.pod.namespace=kube-system")
	if err != nil {
		return err
	}
	var list struct {
		Containers []struct {
			ID       string `json:"id"`
			ImageRef string `json:"imageRef"`
			Image    struct {
				Image string `json:"image"`
			} `json:"image"`
			Labels map[string]string `json:"labels"`
		} `json:"containers"`
	}
	if strings.TrimSpace(out) != "" {
		if err := json.Unmarshal([]byte(out), &list); err != nil {
			return fmt.Errorf("parse crictl ps: %w", err)
		}
	}
	for _, ctr := range list.Containers {
		current, err := c.run(ctx, "docker", "exec", node, "crictl", "inspecti", "-o", "go-template", "--template", "{{.status.id}}", ctr.Image.Image)
		if err != nil || strings.TrimSpace(current) == "" || strings.TrimSpace(current) == ctr.ImageRef {
			continue
		}
		if _, err := fmt.Fprintf(c.out, "Restarting %s with the new image\n", ctr.Labels["io.kubernetes.pod.name"]); err != nil {
			return err
		}
		if _, err := c.run(ctx, "docker", "exec", node, "crictl", "stop", "--timeout", "10", ctr.ID); err != nil {
			return err
		}
	}
	return nil
}

func (c cluster) waitReady(ctx context.Context, since time.Time) error {
	ticker := time.NewTicker(time.Second)
	defer ticker.Stop()
	var last error
	for {
		last = c.client.Health(ctx)
		if last == nil {
			nodes, err := client.Nodes(c.client).List(ctx, client.ListOptions{})
			last = err
			if err == nil {
				ready := map[string]bool{}
				for i := range nodes.Items {
					cond := nodes.Items[i].Status.Condition(corev1.NodeReady)
					if corev1.IsNodeReady(&nodes.Items[i]) && cond.LastHeartbeatTime.After(since) {
						ready[nodes.Items[i].Name] = true
					}
				}
				missing := []string{}
				for _, n := range nodeNames(c.workers) {
					if !ready[n] {
						missing = append(missing, n)
					}
				}
				if len(missing) == 0 {
					return nil
				}
				last = fmt.Errorf("waiting for fresh Ready heartbeats from %s", strings.Join(missing, ", "))
			}
		}
		select {
		case <-ctx.Done():
			return fmt.Errorf("cluster readiness failed: %w (last check: %v); inspect docker compose logs", ctx.Err(), last)
		case <-ticker.C:
		}
	}
}

// down stops the workers first, then removes everything with the
// control-plane node; Pods die with their node containers. With volumes it
// also deletes the nodes' disks, including the etcd data.
func (c cluster) down(ctx context.Context, volumes bool) error {
	stop := c.compose(append([]string{"stop"}, workerNames(c.workers)...)...)
	if _, err := c.run(ctx, stop[0], stop[1:]...); err != nil {
		return err
	}
	down := c.compose("down", "--remove-orphans")
	if volumes {
		down = append(down, "--volumes")
	}
	_, err := c.run(ctx, down[0], down[1:]...)
	return err
}

// runCluster implements `kk cluster up|status|down`.
func runCluster(ctx context.Context, root string, a args) (result error) {
	if len(a.positional) != 1 || (a.positional[0] != "up" && a.positional[0] != "status" && a.positional[0] != "down") {
		return errors.New("usage: kk cluster up [--workers N] | status | down [--volumes]")
	}
	sub := a.positional[0]
	workers := 0
	if v, ok := a.values["workers"]; ok {
		if sub != "up" {
			return errors.New("--workers applies to kk cluster up")
		}
		n, err := parseWorkers(v[len(v)-1])
		if err != nil {
			return err
		}
		workers = n
	}
	token, err := loadToken(root, sub == "up")
	if err != nil {
		return err
	}
	if sub == "status" {
		c := client.New(apiURL(), token)
		if err := c.Health(ctx); err != nil {
			return fmt.Errorf("API unhealthy: %w", err)
		}
		if _, err := fmt.Fprintln(os.Stdout, "API healthy"); err != nil {
			return err
		}
		return newApp(c, os.Stdout, os.Stdin, args{}).run(ctx, "get", args{positional: []string{"nodes"}, values: map[string][]string{}, bools: map[string]bool{}})
	}
	c, err := newCluster(ctx, root, token, os.Stdout)
	if err != nil {
		return err
	}
	if c.cleanup != nil {
		defer func() {
			if err := c.cleanup(); err != nil {
				result = errors.Join(result, fmt.Errorf("clean up temporary Docker config: %w", err))
			}
		}()
	}
	if sub == "up" {
		if workers == 0 {
			workers = c.workers // the count of the last cluster up
		}
		return c.up(ctx, workers)
	}
	volumes := a.boolean("volumes", false)
	if err := c.down(ctx, volumes); err != nil {
		return err
	}
	if volumes {
		_, err = fmt.Fprintln(os.Stdout, "mini-k8s stopped; etcd data and node disks deleted, token preserved")
	} else {
		_, err = fmt.Fprintln(os.Stdout, "mini-k8s stopped; etcd data, node disks and token preserved")
	}
	return err
}

// runImage implements `kk image load IMAGE...`.
func runImage(ctx context.Context, root string, a args) (result error) {
	if len(a.positional) < 2 || a.positional[0] != "load" {
		return errors.New("usage: kk image load IMAGE...")
	}
	token, err := loadToken(root, false)
	if err != nil {
		return err
	}
	c, err := newCluster(ctx, root, token, os.Stdout)
	if err != nil {
		return err
	}
	if c.cleanup != nil {
		defer func() {
			if err := c.cleanup(); err != nil {
				result = errors.Join(result, fmt.Errorf("clean up temporary Docker config: %w", err))
			}
		}()
	}
	return c.loadImages(ctx, a.positional[1:], nodeNames(c.workers)...)
}
